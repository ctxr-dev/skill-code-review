def _fmt(value: Any, places: int = 3) -> str:
    if value is None:
        return "n/a"
    if isinstance(value, float):
        return f"{value:.{places}f}"
    return str(value)


def _fmt_ci(lo: Any, hi: Any, places: int = 3) -> str:
    if lo is None or hi is None:
        return "n/a"
    return f"[{float(lo):.{places}f}, {float(hi):.{places}f}]"



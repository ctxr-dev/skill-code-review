def slowest_timings(
    conn: sqlite3.Connection,
    *,
    scope: str | None = None,
    run_id: str | None = None,
    measured_only: bool = True,
    top: int = 20,
) -> list[dict[str, Any]]:
    """Aggregate the timings table into a ranked slowest-stages view.

    Groups by (scope, name); sums wall_ms and n_calls; counts the distinct PRs a
    stage appeared in; orders by total wall_ms descending. ``measured_only``
    (default) restricts to status='measured' so LLM-self-reported / estimated
    rows never poison the ranking.
    """
    where: list[str] = []
    params: list[Any] = []
    if scope:
        where.append("scope = ?")
        params.append(scope)
    if run_id:
        where.append("run_id = ?")
        params.append(run_id)
    if measured_only:
        where.append("status = 'measured'")
    where_sql = (" WHERE " + " AND ".join(where)) if where else ""
    sql = (
        "SELECT scope, name, COUNT(DISTINCT pr_id) AS prs, SUM(n_calls) AS calls, "
        "ROUND(AVG(wall_ms)) AS avg_ms, SUM(wall_ms) AS total_ms "
        "FROM timings" + where_sql + " GROUP BY scope, name "
        "ORDER BY total_ms DESC NULLS LAST LIMIT ?"
    )
    cur = conn.execute(sql, (*params, int(top)))
    return [dict(r) for r in cur.fetchall()]


def get_experiment(conn: sqlite3.Connection, run_id: str) -> dict[str, Any] | None:
    """Return one experiment row as a dict, or None if no such run_id exists."""
    cur = conn.execute("SELECT * FROM experiments WHERE run_id = ?", (run_id,))
    r = cur.fetchone()
    return dict(r) if r else None


def all_experiments(conn: sqlite3.Connection) -> list[dict[str, Any]]:
    """All experiment rows, oldest first (ts then run_id), as dicts."""
    cur = conn.execute("SELECT * FROM experiments ORDER BY ts ASC, run_id ASC")
    return [dict(r) for r in cur.fetchall()]


def metrics_for(conn: sqlite3.Connection, run_id: str) -> list[dict[str, Any]]:
    """Per-tool metric rows for one run_id, best F1 first, as dicts."""
    cur = conn.execute(
        "SELECT * FROM metrics WHERE run_id = ? ORDER BY f1 DESC NULLS LAST, tool ASC",
        (run_id,),
    )
    return [dict(r) for r in cur.fetchall()]


def latest_proven(conn: sqlite3.Connection) -> dict[str, Any] | None:
    """The most recent PROMOTED (or RAMP) experiment, our live baseline. The proven
    verdicts come from PROVEN_VERDICTS (single source of truth) rather than inline
    SQL literals, so the SQL never drifts from the verdict vocabulary."""
    placeholders = ", ".join("?" for _ in PROVEN_VERDICTS)
    cur = conn.execute(
        f"SELECT * FROM experiments WHERE verdict IN ({placeholders}) "
        "ORDER BY ts DESC, run_id DESC LIMIT 1",
        PROVEN_VERDICTS,
    )
    r = cur.fetchone()
    return dict(r) if r else None


# ---------------------------------------------------------------------------
# The 5-gate PROMOTE predicate (plan 6.3).
# ---------------------------------------------------------------------------
@dataclass(frozen=True)
class GateResult:
    verdict: str  # "promote" | "revert" | "inconclusive"
    gates: dict[str, bool]
    detail: dict[str, Any]

    def to_json(self) -> str:
        return json.dumps(
            {"verdict": self.verdict, "gates": self.gates, "detail": self.detail},
            sort_keys=True,
        )


def summary_stat_gate(
    baseline: dict[str, Any],
    candidate: dict[str, Any],
) -> dict[str, Any]:
    """Pure-stdlib evaluation of the 5-gate predicate from the recorded row means
    and CIs. This is the SINGLE owner of the summary-statistics gate arithmetic:
    it is the standalone path used when scripts/stats.py (which carries the paired
    bootstrap machinery) is not importable, and scripts/stats.py imports it so the
    fallback never drifts from a second copy. It evaluates the gate arithmetic over
    the persisted summary statistics; it does NOT recompute paired bootstrap deltas
    (that requires the per-PR samples and numpy, which live in scripts/stats.py).

    GATE-3 here is approximated by the SIGN of (f1_mean_C - f1_mean_B) and the
    overlap of the two F1 CIs: if the candidate CI lower bound exceeds the baseline
    CI upper bound, the delta CI strictly excludes 0 (a sufficient, conservative
    condition). When the CIs overlap, GATE-3 is reported as not-separated and the
    outcome is inconclusive unless another gate already forced a revert.

    Returns the tracker's mapping contract: {"verdict", "gates", "detail"} with
    lower-cased verdicts ("promote" | "revert" | "inconclusive") and the
    underscored gate keys (gate_1_recall ...) that scripts/stats.py also emits.
    """

    def f(row: dict[str, Any], key: str, default: float = 0.0) -> float:
        v = row.get(key)
        return float(v) if v is not None else default

    rec_b, rec_c = f(baseline, "recall_mean"), f(candidate, "recall_mean")
    fp_b, fp_c = f(baseline, "fp_per_pr_mean"), f(candidate, "fp_per_pr_mean")
    f1_b, f1_c = f(baseline, "f1_mean"), f(candidate, "f1_mean")
    f1lo_b, f1hi_b = f(baseline, "f1_ci_lo"), f(baseline, "f1_ci_hi")
    f1lo_c = f(candidate, "f1_ci_lo")
    std_b = f(baseline, "f1_stdev")
    std_c = f(candidate, "f1_stdev")
    # cost_mean is kept Optional on BOTH sides so a missing cost fails GATE-5
    # CLOSED (we cannot bound the ratio, so we must not silently pass the guard).
    # Symmetry matters: defaulting a missing CANDIDATE cost to 0.0 would make
    # 0.0 <= 1.25*cost_b trivially true and pass GATE-5 on no data, the same
    # fail-open hole the baseline branch avoids.
    # bool is a subclass of int, so a malformed cost_mean: true/false would coerce
    # to 1.0/0.0 and bind GATE-5 on garbage; exclude bool so it reads as missing.
    def _cost(row: dict[str, Any]) -> float | None:
        v = row.get("cost_mean")
        return float(v) if isinstance(v, int | float) and not isinstance(v, bool) else None

    cost_b = _cost(baseline)
    cost_c = _cost(candidate)
    # The PR rung is the sample-size floor input. Distinguish "unknown" (None)
    # from a real zero so a missing/unparseable pr_set_id never collapses to a
    # falsy 0 that bypasses the underpower guard.
    n_prs = _pr_set_rung(candidate.get("pr_set_id"))

    # GATE-1 recall non-regression. We do not have the paired delta CI here, so the
    # point estimate (rec_c - rec_b) stands in for the delta-CI lower bound and the
    # spec tolerance (-0.03) is the binding floor: a recall drop within the tolerance
    # band still passes (matching the CI-based path, which allows lower-95%-CI >=
    # -0.03). The tolerance must be the SOLE constraint here; an extra `rec_c >=
    # rec_b` conjunct would force strict non-regression and make the floor dead code.
    gate1 = (rec_c - rec_b) >= GATE1_RECALL_DELTA_FLOOR
    # GATE-2 noise non-regression. Symmetric: the +0.30 ceiling is the binding
    # constraint (the point estimate stands in for the delta-CI upper bound), so a
    # small fp/PR increase within tolerance still passes. An extra `fp_c <= fp_b`
    # conjunct would force strict non-regression and make the ceiling dead code.
    gate2 = (fp_c - fp_b) <= GATE2_FP_DELTA_CEILING
    # GATE-3 progress: conservative CI separation (candidate lo > baseline hi).
    f1_ci_separated = f1lo_c > f1hi_b
    gate3 = (f1_c > f1_b) and f1_ci_separated
    # GATE-4 stability.
    gate4 = std_c <= (std_b + GATE4_STDEV_SLACK)
    # GATE-5 cost guard. A missing/zero baseline cost cannot bound the ratio, and a
    # missing candidate cost has no value to bound, so EITHER side missing FAILS
    # CLOSED: GATE-5 is red and the run is held INCONCLUSIVE pending a real cost
    # rather than waved through. (Defaulting a missing candidate cost to 0.0 would
    # make 0.0 <= 1.25*cost_b trivially true and pass GATE-5 on no data.)
    # A non-positive proxy cost on EITHER side is missing/invalid telemetry, not a
    # real measurement: zero per-review proxy cost cannot happen on a run that
    # actually dispatched specialists. Treat candidate <= 0 as missing too, symmetric
    # with the baseline, so a 0.0 candidate does not pass 0.0 <= 1.25*cost_b trivially.
    cost_baseline_missing = cost_b is None or cost_b <= 0
    cost_candidate_missing = cost_c is None or cost_c <= 0
    cost_missing = cost_baseline_missing or cost_candidate_missing
    # The trailing ignore[operator] is needed because mypy cannot narrow cost_b /
    # cost_c (float | None) through the `not cost_missing` guard; but cost_missing is
    # True whenever either is None, so the comparison only runs when both are floats.
    gate5 = (not cost_missing) and cost_c <= GATE5_COST_MULTIPLIER * cost_b  # type: ignore[operator]

    gates = {
        "gate_1_recall": gate1,
        "gate_2_noise": gate2,
        "gate_3_progress": gate3,
        "gate_4_stability": gate4,
        "gate_5_cost": gate5,
    }
    underpowered = n_prs is not None and n_prs < MIN_PRS_FOR_PROMOTE
    detail: dict[str, Any] = {
        "recall_delta": round(rec_c - rec_b, 4),
        "fp_per_pr_delta": round(fp_c - fp_b, 4),
        "f1_delta": round(f1_c - f1_b, 4),
        "f1_ci_separated": f1_ci_separated,
        "baseline_f1_ci": [f1lo_b, f1hi_b],
        "candidate_f1_ci_lo": f1lo_c,
        "stdev_delta": round(std_c - std_b, 4),
        "cost_ratio": (
            round(cost_c / cost_b, 4)
            if cost_b is not None and cost_b > 0 and cost_c is not None
            else None
        ),
        "n_prs": n_prs,
        "engine": "fallback-stdlib",
        "underpowered": underpowered,
        "notes": [],
    }
    if cost_baseline_missing:
        detail["notes"].append("cost_baseline_missing")
    if cost_candidate_missing:
        detail["notes"].append("cost_candidate_missing")

    # Outcome rules (plan 6.3): all green -> promote; only GATE-3 straddles 0 ->
    # inconclusive (retry at next rung); any of GATE-1/2/4/5 red -> revert. A
    # missing baseline cost is treated as not-yet-provable, not a regression, so it
    # routes to inconclusive rather than revert.
    hard_gates_ok = gate1 and gate2 and gate4 and gate5
    # Two distinct not-yet-provable cases route to inconclusive (vs a genuine
    # regression -> revert): (a) the only failing gate is GATE-5 because a cost
    # (baseline OR candidate) is missing (the other hard gates pass), or (b) the
    # only failing gate is GATE-3 (the progress CI straddles zero).
    cost_blocked = cost_missing and gate1 and gate2 and gate4
    progress_only_red = hard_gates_ok and not gate3
    if underpowered:
        verdict = VERDICT_INCONCLUSIVE
    elif all(gates.values()):
        verdict = VERDICT_PROMOTE
    elif cost_blocked or progress_only_red:
        verdict = VERDICT_INCONCLUSIVE
    else:
        verdict = VERDICT_REVERT
    return {"verdict": verdict, "gates": gates, "detail": detail}


def run_gate(
    conn: sqlite3.Connection,
    candidate_run: str,
    baseline_run: str,
) -> GateResult:
    """Apply the 5-gate predicate. Prefers scripts.stats.promote_gate (the paired
    bootstrap implementation) via a LAZY import so this module imports cleanly even
    when scripts/stats.py does not exist yet. Falls back to the stdlib summary-stat
    evaluation otherwise.
    """
    baseline = get_experiment(conn, baseline_run)
    candidate = get_experiment(conn, candidate_run)
    if baseline is None:
        raise SystemExit(f"baseline run not found: {baseline_run}")
    if candidate is None:
        raise SystemExit(f"candidate run not found: {candidate_run}")

    # Lazy import: only attempted inside this function so the module is importable
    # without numpy/scipy/statsmodels and without scripts/stats.py present. We
    # narrow to IMPORT errors only: an ImportError/ModuleNotFoundError genuinely
    # means the bench stack is absent, so the stdlib summary-stat path is correct.
    # A different exception (a real bug inside scripts.stats: SyntaxError,
    # AttributeError, a failed numpy import surfacing as ImportError is still an
    # import error) must NOT be swallowed into a silent engine swap, so it
    # propagates and the operator sees it.
    try:
        if str(REPO) not in sys.path:
            sys.path.insert(0, str(REPO))
        from scripts.stats import promote_gate  # type: ignore[import-not-found, import-untyped]
    except (ImportError, ModuleNotFoundError):
        result = summary_stat_gate(baseline, candidate)
        return GateResult(
            verdict=result["verdict"],
            gates={str(k): bool(v) for k, v in result["gates"].items()},
            detail=dict(result["detail"]),
        )

    # promote_gate comes from scripts.stats, whose return mypy widens to `object`
    # in some invocation contexts; cast to the documented mapping contract so the
    # .get() / dict() normalization below type-checks when mypy runs on this file
    # directly.
    raw = cast(Mapping[str, object], promote_gate(baseline, candidate))
    # scripts.stats.promote_gate is expected to return a mapping with at least
    # {"verdict", "gates", "detail"}. Normalize defensively so a partial return
    # still produces a usable GateResult.
    verdict = str(raw.get("verdict", VERDICT_INCONCLUSIVE))
    raw_gates = cast(Mapping[str, object], raw.get("gates", {}))
    raw_detail = cast(Mapping[str, object], raw.get("detail", {}))
    gates = {str(k): bool(v) for k, v in raw_gates.items()}
    detail = dict(raw_detail)
    detail.setdefault("engine", "scripts.stats.promote_gate")
    return GateResult(verdict=verdict, gates=gates, detail=detail)



def cmd_record(args: argparse.Namespace) -> int:
    config = _load_json_arg(args.config)
    metrics = _load_json_arg(args.metrics) or []
    findings = _load_json_arg(args.findings) or []
    row: dict[str, Any] = {
        "run_id": args.run_id,
        "ts": _now(),
        "git_sha": args.git_sha or _git_sha(),
        "pr_set_id": args.pr_set,
        "baseline_tag": args.baseline_tag,
        "backend": args.backend,
        "config_json": config,
        "lever": args.lever,
        "hypothesis": args.hypothesis,
        "diff_stat": args.diff_stat,
        "n_rounds": args.n_rounds,
        "recall_mean": args.recall,
        "recall_ci_lo": args.recall_ci_lo,
        "recall_ci_hi": args.recall_ci_hi,
        "precision_mean": args.precision,
        "f1_mean": args.f1,
        "f1_ci_lo": args.f1_ci_lo,
        "f1_ci_hi": args.f1_ci_hi,
        "fp_per_pr_mean": args.fp_per_pr,
        "cost_mean": args.cost,
        "f1_stdev": args.f1_stdev,
        "verdict": args.verdict,
        "calibration_tag": args.calibration_tag,
        "notes": args.notes,
    }
    # The 5-gate predicate (the `gate` subcommand) is the SOLE authority for the
    # proven-baseline verdicts: latest_proven keys off PROVEN_VERDICTS, so letting
    # `record` write a promote/ramp verdict by hand would synthesise a baseline that
    # never cleared the gate. record may set a non-promoting placeholder only.
    if args.verdict is not None and args.verdict in PROVEN_VERDICTS:
        raise SystemExit(
            f"refusing to record verdict '{args.verdict}': the proven-baseline "
            f"verdicts {PROVEN_VERDICTS} are set only by the gate subcommand. "
            "Record without --verdict, then run `experiments.py gate ... --apply`."
        )
    if not args.apply:
        print("DRY-RUN: would record experiment row (pass --apply to persist):")
        print(json.dumps({k: v for k, v in row.items() if v is not None}, indent=2, default=str))
        print(f"plus {len(metrics)} metric row(s), {len(findings)} finding row(s).")
        return 0
    conn = connect(args.db)
    try:
        init_db(conn)
        upsert_experiment(conn, row)
        for m in metrics:
            upsert_metric(conn, {**m, "run_id": args.run_id})
        for fnd in findings:
            cols = (
                "run_id",
                "pr_id",
                "tool",
                "finding_idx",
                "defect_confidence",
                "severity",
                "matched",
                "golden_count",
            )
            payload = {c: fnd.get(c) for c in cols}
            payload["run_id"] = args.run_id
            col_sql = ", ".join(cols)
            marks = ", ".join(f":{c}" for c in cols)
            conn.execute(
                f"INSERT OR REPLACE INTO findings ({col_sql}) VALUES ({marks})", payload
            )
        conn.commit()
    finally:
        conn.close()
    print(f"recorded run {args.run_id} into {args.db}")
    return 0


def cmd_ci(args: argparse.Namespace) -> int:
    """Attach bootstrap CIs to a recorded run. The CI computation itself lives in
    scripts/stats.py (numpy bootstrap). This subcommand persists CI values passed
    on the command line, so the tracker stays pure-stdlib; the heavy lifting is a
    seam the harness fills.
    """
    conn = connect(args.db)
    try:
        init_db(conn)
        row = get_experiment(conn, args.run_id)
        if row is None:
            raise SystemExit(f"run not found: {args.run_id}")
        updates = {
            "recall_ci_lo": args.recall_ci_lo,
            "recall_ci_hi": args.recall_ci_hi,
            "f1_ci_lo": args.f1_ci_lo,
            "f1_ci_hi": args.f1_ci_hi,
        }
        updates = {k: v for k, v in updates.items() if v is not None}
        if not updates:
            print("no CI values supplied; nothing to do.")
            return 0
        if not args.apply:
            print(f"DRY-RUN: would set on {args.run_id}: "
                  f"{json.dumps(updates)} (pass --apply).")
            return 0
        sets = ", ".join(f"{k} = :{k}" for k in updates)
        conn.execute(
            f"UPDATE experiments SET {sets} WHERE run_id = :run_id",
            {**updates, "run_id": args.run_id},
        )
        conn.commit()
    finally:
        conn.close()
    print(f"updated CIs on {args.run_id}")
    return 0



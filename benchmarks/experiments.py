def render_leaderboard(conn: sqlite3.Connection) -> str:
    """Best tool rows across all recorded runs, ranked by F1 (plan 8)."""
    cur = conn.execute(
        "SELECT m.*, e.pr_set_id AS pr_set_id, e.ts AS ts "
        "FROM metrics m LEFT JOIN experiments e ON e.run_id = m.run_id "
        "ORDER BY m.f1 DESC NULLS LAST, m.tool ASC"
    )
    rows = [dict(r) for r in cur.fetchall()]
    lines: list[str] = [DO_NOT_EDIT, "# Benchmark LEADERBOARD", ""]
    lines.append(f"Generated: {_now()}")
    lines.append("")
    if not rows:
        lines.append("No tool metrics recorded yet.")
        lines.append("")
        return "\n".join(lines)
    lines.append("| tool | run_id | pr_set | recall | precision | F1 | FP/PR | $/review |")
    lines.append("|---|---|---|---|---|---|---|---|")
    for r in rows:
        star = " (skill)" if str(r.get("tool", "")).startswith(SKILL_TOOL_PREFIX) else ""
        lines.append(
            f"| {r.get('tool')}{star} | {r.get('run_id')} | {r.get('pr_set_id') or 'n/a'} | "
            f"{_fmt(r.get('recall'), 2)} | {_fmt(r.get('precision'), 2)} | "
            f"{_fmt(r.get('f1'), 2)} | {_fmt(r.get('fp_per_pr'), 2)} | "
            f"{_fmt(r.get('usd_per_review'), 4)} |"
        )
    lines.append("")
    return "\n".join(lines)


